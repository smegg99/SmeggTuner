#!/usr/bin/env python3
"""Generate the Android host from the repository's pinned Wails module."""

import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).resolve().parent
CONFIG = json.loads((SOURCE / "config.json").read_text())
OUT = ROOT / "build/android"


def replace(path, old, new, count=1):
    text = path.read_text()
    if text.count(old) != count:
        raise RuntimeError(f"{path}: expected {count} occurrences of {old!r}; review Wails template")
    path.write_text(text.replace(old, new))


module = subprocess.check_output(
    ["go", "list", "-m", "-f", "{{.Dir}}", "github.com/wailsapp/wails/v3"],
    cwd=ROOT, text=True,
).strip()
template = Path(module) / "internal/commands/build_assets/android"


def overlay():
    directory = OUT / "gen"
    directory.mkdir(parents=True, exist_ok=True)
    entry = directory / "main_android.gen.go"
    entry.write_text('''//go:build android

// Code generated by build/android-support/generate.py. DO NOT EDIT.
package main

import (
    "sync"
    "github.com/wailsapp/wails/v3/pkg/application"
)

var androidMainOnce sync.Once

func init() {
    application.RegisterAndroidMain(func() {
        androidMainOnce.Do(func() { go main() })
    })
}
''')
    (OUT / "overlay.json").write_text(json.dumps({
        "Replace": {str(ROOT / "backend/main_android.gen.go"): str(entry)},
    }, indent=2) + "\n")


if sys.argv[1:] == ["--overlay"]:
    overlay()
    sys.exit(0)
if sys.argv[1:]:
    raise SystemExit("usage: generate.py [--overlay]")
# Preserve Gradle caches and built JNI libraries across regeneration.
OUT.mkdir(parents=True, exist_ok=True)
OUT.chmod(0o755)
for path in template.rglob("*"):
    target = OUT / path.relative_to(template)
    if path.is_dir():
        target.mkdir(parents=True, exist_ok=True)
        target.chmod(0o755)
    elif path.is_file():
        if target.exists():
            target.chmod(0o644)
        shutil.copyfile(path, target)
(OUT / "gradlew").chmod(0o755)

gradle = OUT / "app/build.gradle"
version = (ROOT / "VERSION").read_text().strip()
major, minor, patch = map(int, version.split("."))
if minor >= 1000 or patch >= 1000:
    raise ValueError("Android version code requires minor and patch below 1000")
code = major * 1_000_000 + minor * 1000 + patch
if not 0 < code <= 2_100_000_000:
    raise ValueError("Android version code outside Play Store range")
for old, new in [
    ('applicationId "com.wails.app"', f'applicationId "{CONFIG["applicationId"]}"'),
    ('compileSdk 35', f'compileSdk {CONFIG["targetSdk"]}'),
    ('minSdk 21', f'minSdk {CONFIG["minSdk"]}'),
    ('targetSdk 35', f'targetSdk {CONFIG["targetSdk"]}'),
    ('versionCode 1', f'versionCode {code}'),
    ('versionName "1.0"', f'versionName "{version}"'),
    ('    buildFeatures {', f'    buildToolsVersion "{CONFIG["buildTools"]}"\n    ndkVersion "{CONFIG["ndk"]}"\n\n    buildFeatures {{'),
    ('        applicationId ', f'        buildConfigField "int", "MIN_WEBVIEW_MAJOR", "{CONFIG["webViewMinMajor"]}"\n        applicationId '),
]:
    replace(gradle, old, new)
replace(gradle, "jniLibs.srcDirs = ['src/main/jniLibs']", "jniLibs.srcDirs = [providers.gradleProperty('wailsJniDir').getOrElse('src/main/jniLibs')]")
replace(OUT / "build.gradle", "version '8.7.3'", f"version '{CONFIG['agp']}'")
wrapper = OUT / "gradle/wrapper/gradle-wrapper.properties"
replace(wrapper, "gradle-9.2.1-bin.zip", f"gradle-{CONFIG['gradle']}-bin.zip")
with wrapper.open("a") as f:
    f.write(f"\ndistributionSha256Sum={CONFIG['gradleSha256']}\n")

taskfile = OUT / "Taskfile.yml"
replace(taskfile, "MIN_SDK: '21'", f"MIN_SDK: '{CONFIG['minSdk']}'")
replace(taskfile, "TARGET_SDK: '35'", f"TARGET_SDK: '{CONFIG['targetSdk']}'")
replace(taskfile, 'default "com.wails.app"', f'default "{CONFIG["applicationId"]}"')
# malgo 0.11.25 passes ARM32-only compiler flags to ARM64 unless noasm is set.
replace(taskfile, '-tags production,android', '-tags production,android,noasm', 2)
replace(taskfile, '-tags android,debug', '-tags android,debug,noasm', 2)
replace(taskfile, '- wails3 android overlay:gen -out build/android/overlay.json -config build/config.yml', '- python3 build/android-support/generate.py --overlay')
replace(taskfile, "- wails3 generate bindings -f '-tags android' -clean=true", "- go tool wails3 generate bindings -f '-tags android' -clean=true -d frontend/bindings ./backend")
replace(taskfile, '-o build/android/app/src/main/jniLibs/$JNI_DIR/libwails.so\n', '-o build/android/app/src/main/jniLibs/$JNI_DIR/libwails.so ./backend\n')
# Binding generation runs on the host. An Android build tag without GOOS=android
# mixes desktop C headers and JNI headers in go/packages.
replace(taskfile, 'BUILD_FLAGS:\n            ref: .BUILD_FLAGS', 'BUILD_FLAGS: \'{{if eq OS "linux"}}-tags gtk3{{end}}\'')
replace(taskfile, '/com.wails.app.MainActivity', '/com.wails.app.LauncherActivity', 4)
replace(taskfile, '      - \'"{{.ADB}}" uninstall {{.APP_ID}} 2>/dev/null || true\'\n', '', 2)
replace(taskfile, '        "{{.ADB}}" -s "$DEVICE" uninstall {{.APP_ID}} 2>/dev/null || true\n', '', 2)

# Wails beta.34 declares API 21 but uses an API 24 network callback at startup.
replace(
    OUT / "app/src/main/java/com/wails/app/MainActivity.java",
    '                connectivityManager.registerDefaultNetworkCallback(networkCallback);',
    '''                if (Build.VERSION.SDK_INT >= 24) {
                    connectivityManager.registerDefaultNetworkCallback(networkCallback);
                } else {
                    connectivityManager.registerNetworkCallback(
                            new android.net.NetworkRequest.Builder()
                                    .addCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET)
                                    .build(), networkCallback);
                }''',
)
replace(
    OUT / "app/src/main/java/com/wails/app/MainActivity.java",
    '            Network active = connectivityManager.getActiveNetwork();',
    '''            Network active = null;
            if (Build.VERSION.SDK_INT >= 23) {
                active = connectivityManager.getActiveNetwork();
            } else {
                for (Network network : connectivityManager.getAllNetworks()) {
                    android.net.NetworkInfo info = connectivityManager.getNetworkInfo(network);
                    if (info != null && info.isConnected()) {
                        active = network;
                        break;
                    }
                }
            }''',
)

manifest = OUT / "app/src/main/AndroidManifest.xml"
replace(manifest, '    <queries>', '    <uses-permission android:name="android.permission.RECORD_AUDIO" />\n\n    <queries>')
replace(manifest, '        <activity\n', '        <activity android:name=".LauncherActivity" android:exported="true">\n            <intent-filter>\n                <action android:name="android.intent.action.MAIN" />\n                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>\n        </activity>\n\n        <activity\n')
replace(manifest, '            <intent-filter>\n                <action android:name="android.intent.action.MAIN" />\n                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>\n        </activity>\n\n        <provider', '        </activity>\n\n        <provider')
shutil.copyfile(SOURCE / "LauncherActivity.java", OUT / "app/src/main/java/com/wails/app/LauncherActivity.java")
for java in (SOURCE / "java").glob("*.java"):
    shutil.copyfile(java, OUT / "app/src/main/java/com/wails/app" / java.name)
for resource in (SOURCE / "res").rglob("*.xml"):
    target = OUT / "app/src/main/res" / resource.relative_to(SOURCE / "res")
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(resource, target)
activity = OUT / "app/src/main/java/com/wails/app/MainActivity.java"
# Honor the app's fitted desktop viewport on Android.
replace(activity, '        settings.setJavaScriptEnabled(true);', '        settings.setJavaScriptEnabled(true);\n        settings.setUseWideViewPort(true);')
replace(activity, '        super.onCreate(savedInstanceState);', '''        super.onCreate(savedInstanceState);
        if (!WebViewRequirement.allowed(this)) {
            startActivity(new android.content.Intent(this, LauncherActivity.class));
            finish();
            return;
        }''')
replace(activity, '        super.onStart();', '        super.onStart();\n        if (tunerHost == null) return;')
replace(manifest, 'android:name=".MainActivity"\n            android:exported="true"', 'android:name=".MainActivity"\n            android:exported="false"')
replace(activity, '    private WailsBridge bridge;', '    private WailsBridge bridge;\n    private AndroidHost tunerHost;\n    private BackNavigation tunerBackNavigation;')
replace(activity, '        bridge = new WailsBridge(this);', '        tunerHost = new AndroidHost(this);\n        bridge = new WailsBridge(this);')
replace(activity, '        super.onActivityResult(requestCode, resultCode, data);', '        if (tunerHost != null && tunerHost.onActivityResult(requestCode, resultCode, data)) return;\n        super.onActivityResult(requestCode, resultCode, data);')
replace(activity, '        super.onDestroy();', '        if (tunerBackNavigation != null) tunerBackNavigation.close();\n        if (tunerHost != null) tunerHost.close();\n        super.onDestroy();')
replace(activity, '        webView.addJavascriptInterface(new WailsJSBridge(bridge, webView), "wails");', '        webView.addJavascriptInterface(new WailsJSBridge(bridge, webView), "wails");\n        tunerBackNavigation = new BackNavigation(this, webView);')
replace(activity, '''    @Override
    public void onBackPressed() {
        if (webView != null && webView.canGoBack()) {
            webView.goBack();
        } else {
            super.onBackPressed();
        }
    }
''', '')
replace(manifest, '        android:allowBackup="true"', '        android:allowBackup="true"\n        android:enableOnBackInvokedCallback="true"')
# The WebView occupies the safe drawing area; CSS and overlays use its viewport.
replace(activity, '        setContentView(R.layout.activity_main);', '''        setContentView(R.layout.activity_main);
        android.view.View content = findViewById(R.id.main_container);
        androidx.core.view.ViewCompat.setOnApplyWindowInsetsListener(content, (view, insets) -> {
            androidx.core.graphics.Insets safe = insets.getInsets(
                    androidx.core.view.WindowInsetsCompat.Type.systemBars()
                    | androidx.core.view.WindowInsetsCompat.Type.displayCutout()
                    | androidx.core.view.WindowInsetsCompat.Type.ime());
            view.setPadding(safe.left, safe.top, safe.right, safe.bottom);
            return insets;
        });
        androidx.core.view.ViewCompat.requestApplyInsets(content);''')
replace(OUT / "app/src/main/res/values/strings.xml", 'Wails App', 'SmeggTuner')
for density, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
    directory = OUT / f"app/src/main/res/mipmap-{density}"
    for name in ["ic_launcher.png", "ic_launcher_round.png"]:
        subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), str(ROOT / "assets/smeggtuner-app-icon.svg"), "-o", str(directory / name)], check=True)
print(f"Generated {OUT.relative_to(ROOT)}: {version}, API {CONFIG['minSdk']}..{CONFIG['targetSdk']}")
overlay()
